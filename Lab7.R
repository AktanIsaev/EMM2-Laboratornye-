# Моделирование процесса U_t до t_max
simulate_U <- function(U0, c, lambda, mu, t_max) {
  T <- c(0) # Время T_i
  U <- c(U0) # Капитал U(T_i)
  
  while (sum(T) < t_max) {
    tau <- rexp(1, lambda) # Интервал
    X <- rexp(1, 1 / mu) # Выплата
    
    U <- c(U, U[length(U)] + c * tau - X) # Следующий капитал
    T <- c(T, tau) # Добавляем интервал
  }
  
  list(T = cumsum(T), U = U) # Возвращаем процесс
}

# Параметры
t_max <- 100 # Макс. время
mu <- 1 # Среднее выплат
c1 <- 3 # Выполняется (15)
c2 <- 1.5 # Не выполняется (15)

# Случай (a): U0 = 50, (15) выполняется
res1 <- simulate_U(U0 = 50, c = c1, lambda = lambda, mu = mu, t_max = t_max)

# Случай (b): U0 = 50, (15) не выполняется
res2 <- simulate_U(U0 = 50, c = c2, lambda = lambda, mu = mu, t_max = t_max)


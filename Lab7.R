# Задание 4 ----

# Задаем параметры

N <- 1000        
t_max <- 1000    
c <- 1           
lambda <- 0.3   
mu <- 3          
U0 <- 100   

# Вектор для хранения индикаторов разорения
ruin_indicators <- numeric(N)

# Цикл для моделирования N реализаций процесса и расчета разорения
for (i in 1:N) {
  U <- U0  # нач капитал
  T <- 0   # нач момент времени
  
  # Моделирование процесса до достижения t_max или разорения
  while (T < t_max && U >= 0) {
    tau <- rexp(1, rate = lambda)  # время до следующего страхового случая
    T <- T + tau # обновление времени
    if (T >= t_max) break # остановка, если достигнут предел времени
    
    X <- rexp(1, rate = 1/mu) # страховая выплата
    U <- U + c * tau - X # обновление капитала компании
    
    if (U < 0) { # проверка на разорение
      ruin_indicators[i] <- 1 # отмечаем разорение
      break
    }
  }
}

# Расчет выборочной вероятности разорения
psi_hat <- sum(ruin_indicators) / N  

# Вывод результата
cat("Выборочная вероятность разорения компании:", psi_hat, "\n")

# Проверка условия (16) с заменой psi(u) на psi_hat

# Параметры для расчета psi_bound
p <- c / (lambda * mu) - 1
psi_bound <- exp(- (1 / mu) * (p / (1 + p)) * U0)

cat("Граница вероятности разорения по неравенству Лундберга:", psi_bound, "\n")

# Граница вероятности разорения больше выборочной вероятности разорения,
# значит условие (16) выполняется


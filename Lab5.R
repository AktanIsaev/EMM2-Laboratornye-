     main = "Ансамбль реализаций броуновского движения", 
     xlab = "Время (t)", 
     ylab = "B(t)", 
     xlim = c(0, k_max * delta), 
     ylim = range(-1.5, 1.5)) # Устанавливаем пределы Y для лучшей визуализации

# Генерируем и отображаем 200 реализаций
for (i in 1:num_realizations) {
  # Генерируем случайные приращения для каждой реализации
  epsilon <- rnorm(n, mean = 0, sd = sqrt(delta)) 
  B <- numeric(n) # Сбрасываем вектор для новой реализации
  
  for (k in 2:n) {
    B[k] <- B[k - 1] + epsilon[k] # Заполняем вектор
  }
  
  # Добавляем реализацию на график, с полупрозрачным синим цветом
  lines(seq(0, k_max * delta, by = delta), B, col = adjustcolor("blue", alpha.f = 0.1), lty = 1, cex = 0.5)
}


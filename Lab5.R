set.seed(123) # Фиксируем случайные значения для повторяемости эксперимента

# Задание 2 ----

# Устанавливаем параметры моделирования
delta <- 0.0001 # Шаг дискретизации
k_max <- 1000 # Максимальное значение k (количество шагов)
n <- k_max + 1 # Количество точек (включая начальную точку)

# Генерируем случайные приращения
epsilon <- rnorm(n, mean = 0, sd = sqrt(delta)) # Нормальные случайные величины

# Инициализируем вектор для броуновского движения
B <- numeric(n) # Создаем вектор с нулями

# Заполняем вектор B броуновским движением
for (k in 2:n) {
  B[k] <- B[k - 1] + epsilon[k] # Каждое новое значение <- предыдущее + случайное приращение
}

# Визуализация результата
plot(seq(0, k_max * delta, by = delta), B, type = "l", 
     main = "Моделирование броуновского движения", 
     xlab = "Время (t)", 
     ylab = "B(t)", 
     col = "blue", 
     lwd = 1)

# Добавление сетки для удобства восприятия
grid()


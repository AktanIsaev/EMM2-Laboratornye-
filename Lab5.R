     main = "Ансамбль реализаций геометрического броуновского движения", 
     xlab = "Время (k)", 
     ylab = "S_t", 
     xlim = c(0, k_max * delta), 
     ylim = range(0, 2)) # Устанавливаем пределы Y для лучшей визуализации

# Генерируем и отображаем 200 реализаций геометрического броуновского движения
for (i in 1:num_realizations) {
  # Генерируем случайные приращения для каждой реализации
  epsilon <- rnorm(k_max, mean = 0, sd = sqrt(delta))  # Генерация случайных величин
  S <- numeric(k_max + 1)  # Сбрасываем вектор для новой реализации
  S[1] <- S0  # Устанавливаем начальное значение
  
  for (k in 1:k_max) {
    Bt <- sum(epsilon[1:k])  # Используем сумму приращений до k
    S[k + 1] <- S[1] * exp((a - sigma^2 / 2) * (k * delta) + sigma * Bt)  # Дискретная версия формулы
  }
  
  # Добавляем реализацию на график
  lines(seq(0, k_max * delta, by = delta), S, col = adjustcolor("blue", alpha.f = 0.1), lty = 1)
}

